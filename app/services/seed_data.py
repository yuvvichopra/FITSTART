def seed_initial_data():
    """Seeds verified food items into database if empty."""
    if FoodItem.query.first() is not None:
        return

    for item_data in SEED_FOODS:
        food = FoodItem(**item_data)
        db.session.add(food)
    
    try:
        db.session.commit()
    except Exception as e:
        db.session.rollback()
        raise e
